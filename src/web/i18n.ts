export function normalizeUiLanguage(raw: unknown): UiLanguage | undefined {
  if (typeof raw !== "string") return undefined;
  const trimmed = raw.trim();
  return (UI_LANGUAGES as readonly string[]).includes(trimmed) ? (trimmed as UiLanguage) : undefined;
}

export interface UiLanguageStorage {
  getItem(key: string): string | null;
  setItem(key: string, value: string): void;
}

function safeStorage(): UiLanguageStorage | null {
  try {
    return typeof localStorage === "undefined" ? null : localStorage;
  } catch {
    return null;
  }
}

export function readStorageItem(key: string, storage: UiLanguageStorage | null = safeStorage()): string | null {
  if (!storage) return null;
  try {
    return storage.getItem(key);
  } catch {
    return null;
  }
}

export function writeStorageItem(
  key: string,
  value: string,
  storage: UiLanguageStorage | null = safeStorage(),
): boolean {
  if (!storage) return false;
  try {
    storage.setItem(key, value);
    return true;
  } catch {
    return false;
  }
}

export function readStoredUiLanguage(storage: UiLanguageStorage | null = safeStorage()): UiLanguage {
  return normalizeUiLanguage(readStorageItem(UI_LANGUAGE_STORAGE_KEY, storage)) ?? DEFAULT_UI_LANGUAGE;
}

export function persistUiLanguage(
  language: UiLanguage,
  storage: UiLanguageStorage | null = safeStorage(),
): boolean {
  return writeStorageItem(UI_LANGUAGE_STORAGE_KEY, language, storage);
}

export function uiLanguageName(language: UiLanguage): string {
  return language === "en" ? "English" : "简体中文";
}

export function hasMessage(key: string): key is MessageKey {
  return Object.prototype.hasOwnProperty.call(zhCN, key);
}

function interpolate(template: string, params?: MessageParams, language: UiLanguage = DEFAULT_UI_LANGUAGE): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name];
    if (value === undefined || value === null) return match;
    if (Array.isArray(value)) {
      const sep = language === "en" ? "; " : "；";
      return value
        .map((item) => (hasMessage(item.key) ? t(language, item.key, item.params) : (item.key ?? "")))
        .filter(Boolean)
        .join(sep);
    }
    if (typeof value === "object") {
      return hasMessage(value.key) ? t(language, value.key, value.params) : (value.key ?? match);
    }
    return String(value);
  });
}

export function t(language: UiLanguage, key: MessageKey, params?: MessageParams): string {
  const primary = CATALOGS[language] ?? CATALOGS[DEFAULT_UI_LANGUAGE];
  const template = primary[key] ?? CATALOGS[DEFAULT_UI_LANGUAGE][key] ?? key;
  return interpolate(template, params, language);
}

/** Translates a dynamic message key (e.g. from core validity refs) with readable fallback. */
export function translateRef(
  language: UiLanguage,
  key: string | null | undefined,
  fallback: string,
  params?: MessageParams,
): string {
  if (key && hasMessage(key)) return t(language, key, params);
  return fallback;
}

export function uiMessage(
  language: UiLanguage,
  ref: UiMessageRef | null | undefined,
  fallback: string,
): string {
  if (!ref) return fallback;
  return translateRef(language, ref.key, fallback, ref.params);
}

export function pluralMessage(
  language: UiLanguage,
  count: number,
  oneKey: MessageKey,
  otherKey: MessageKey,
  params?: MessageParams,
): string {
  const key = language === "en" && count === 1 ? oneKey : otherKey;
  return t(language, key, { count: formatNumber(language, count), ...params });
}

export function formatNumber(language: UiLanguage, value: number): string {
  try {
    return new Intl.NumberFormat(LOCALES[language]).format(value);
  } catch {
    return String(value);
  }
}

/** Deterministic date-time text, always rendered in the explicit UI locale. */
export function formatDateTime(language: UiLanguage, ms: number): string {
  const date = new Date(ms);
  if (Number.isNaN(date.getTime())) return "-";
  try {
    return new Intl.DateTimeFormat(LOCALES[language], {
      month: "2-digit",
      day: "2-digit",
      hour: "2-digit",
      minute: "2-digit",
      second: "2-digit",
      hour12: false,
    }).format(date);
  } catch {
    const pad = (n: number) => String(n).padStart(2, "0");
    return `${date.getMonth() + 1}-${pad(date.getDate())} ${pad(date.getHours())}:${pad(date.getMinutes())}:${pad(date.getSeconds())}`;
  }
}

export function formatRelativeTime(language: UiLanguage, ms: number): string {
  const diffSec = Math.max(0, Math.floor((Date.now() - ms) / 1000));
  try {
    const rtf = new Intl.RelativeTimeFormat(LOCALES[language], { numeric: "auto" });
    if (diffSec < 60) return rtf.format(0, "second");
    if (diffSec < 3600) return rtf.format(-Math.floor(diffSec / 60), "minute");
    if (diffSec < 86400) return rtf.format(-Math.floor(diffSec / 3600), "hour");
    return rtf.format(-Math.floor(diffSec / 86400), "day");
  } catch {
    if (diffSec < 60) return language === "en" ? "just now" : "刚刚";
    if (diffSec < 3600) return language === "en" ? `${Math.floor(diffSec / 60)} min ago` : `${Math.floor(diffSec / 60)} 分钟前`;
    if (diffSec < 86400) return language === "en" ? `${Math.floor(diffSec / 3600)} hr ago` : `${Math.floor(diffSec / 3600)} 小时前`;
    return language === "en" ? `${Math.floor(diffSec / 86400)} days ago` : `${Math.floor(diffSec / 86400)} 天前`;
  }
}

