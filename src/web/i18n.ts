/**
 * Keeps the stable error message key and raw detail separate so already-visible
 * feedback can be re-rendered in the language currently selected by the user.
 */
export interface LocalizedError {
  key: MessageKey | null;
  params?: MessageParams;
  text: string;
}

export function describeClientErrorRef(err: unknown): LocalizedError {
  if (err instanceof ApiClientError) {
    const msgKey = typeof err.details?.messageKey === "string" ? err.details.messageKey : null;
    if (msgKey && hasMessage(msgKey)) {
      const rawParams = err.details?.messageParams;
      const msgParams: MessageParams | undefined =
        rawParams && typeof rawParams === "object"
          ? Object.fromEntries(
              Object.entries(rawParams as Record<string, unknown>).filter(
                ([, v]) => typeof v === "string" || typeof v === "number" || v === null || v === undefined,
              ),
            ) as MessageParams
          : undefined;
      return {
        key: msgKey,
        params: msgParams,
        text: err.message?.trim() ?? "",
      };
    }
    const upstreamCode = err.details?.upstreamErrorCode;
    if (upstreamCode === "gitee_api_http_error") {
      const status = Number(err.details?.upstreamStatus ?? err.details?.httpStatus ?? 0);
      const rawDetail = typeof err.details?.upstreamDetail === "string" ? err.details.upstreamDetail.trim() : "";
      const detail = rawDetail || `HTTP ${status || 500}`;
      if (status > 0) {
        return {
          key: "gitee.apiHttpError",
          params: { status, detail },
          text: detail,
        };
      }
    }
    if (upstreamCode === "gitee_network_error") {
      const detail = typeof err.details?.upstreamDetail === "string" ? err.details.upstreamDetail.trim() : "";
      if (detail) {
        return {
          key: "gitee.networkError",
          params: { detail },
          text: detail,
        };
      }
    }
    if (err.code === "acceptance_gate_failed" && Array.isArray(err.details?.blockerRefs)) {
      const validRefs = (err.details.blockerRefs as unknown[]).filter(
        (r): r is UiMessageRef =>
          Boolean(r) &&
          typeof r === "object" &&
          typeof (r as { key?: unknown }).key === "string" &&
          hasMessage((r as { key: string }).key),
      );
      if (validRefs.length > 0) {
        return {
          key: "accept.errGateBlocked",
          params: { blockers: validRefs },
          text: err.message?.trim() ?? "",
        };
      }
    }
    const baseKey = ERROR_CODE_KEYS[err.code] ?? "error.request_failed";
    const detail = err.message?.trim();
    if (!detail || ERROR_CODE_KEYS_REQUIRING_DETAIL.has(err.code)) {
      return { key: baseKey, text: detail ?? "" };
    }
    return {
      key: "error.withDetail",
      params: { message: { key: baseKey }, detail },
      text: detail,
    };
  }
  if (err instanceof Error && err.message) {
    if (/fetch|network|load failed/i.test(err.message)) {
      return { key: "error.network", text: err.message };
    }
    return { key: null, text: err.message };
  }
  return { key: "toast.operationFailed", text: "" };
}

/** Localizes stable API error codes while keeping server-specific detail readable. */
export function describeClientError(language: UiLanguage, err: unknown): string {
  const ref = describeClientErrorRef(err);
  return ref.key ? t(language, ref.key, ref.params) : ref.text;
}

